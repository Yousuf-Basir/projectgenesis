import assert from 'node:assert/strict';
import {Simulation} from '../server/simulation/simulation.js';
import {routeFieldHarvest,foragingNeed} from '../server/simulation/adaptive-morphology.js';
const simulation=new Simulation();simulation.stop();
simulation.organisms=simulation.organisms.slice(0,2);simulation.bonds.clear();
const [source,recipient]=simulation.organisms;
source.x=10;source.y=10;recipient.x=11;recipient.y=10;
source.energy=300;recipient.energy=0;
simulation.bonds.set(simulation.bondKey(source.id,recipient.id),{firstId:source.id,secondId:recipient.id,strength:1,reserve:3});
const total=()=>simulation.organisms.reduce((sum,member)=>sum+member.energy,0)+[...simulation.bonds.values()].reduce((sum,bond)=>sum+bond.reserve,0);
const before=total();
routeFieldHarvest(simulation,source,50);
assert.ok(recipient.energy>0,'weak connected members must receive support');
assert.ok(simulation.morphologyStats.fieldBondFunding>0,'remaining earned surplus may fund existing bonds');
assert.ok(Math.abs(before-total()-(simulation.energyEconomics.losses.fieldSupport??0))<1e-8,'all transfers must be paid, with only declared loss');
assert.ok(source.energy>=simulation.getReproductionEnergyFloor(source));
source.energy=simulation.getReproductionEnergyFloor(source)-1;recipient.energy=0;
const held=total();const prior=source.energy;
routeFieldHarvest(simulation,source,50);
assert.equal(source.energy,prior);assert.equal(total(),held,'routing must not spend protected reproduction energy');
assert.equal(foragingNeed({foragingOperatingCost:1,foragingIncome:2},{scarcitySensingEnabled:true}),.1);
assert.equal(foragingNeed({foragingOperatingCost:1,foragingIncome:0},{scarcitySensingEnabled:true}),1);
assert.equal(foragingNeed({foragingOperatingCost:1,foragingIncome:2},{scarcitySensingEnabled:false}),1);
console.log('Paid field support/reserves, source floor and bounded metabolic response passed.');
process.exit(0);
