import assert from 'node:assert/strict';
import { Simulation } from '../server/simulation/simulation.js';
import { shrinkAtRiskComponents } from '../server/simulation/adaptive-shrinking.js';
const simulation = new Simulation();
simulation.stop();
simulation.config.bond.adaptiveShrinking.enabled = true;
simulation.organisms = simulation.organisms.slice(0, 4);
simulation.bonds.clear();
simulation.organisms.forEach((member, index) => {member.x = 10 + index % 2; member.y = 10 + Math.floor(index / 2); member.energy = 2; member.age = 100;});
const [a,b,c,tail] = simulation.organisms;
for (const [first,second] of [[a,b],[b,c],[c,a],[a,tail]]) simulation.bonds.set(simulation.bondKey(first.id,second.id), {firstId:first.id, secondId:second.id, reserve:1,strength:1});
const ids = simulation.organisms.map(member => member.id);
const key = simulation.componentReserveKey(ids);
simulation.componentReserves.set(key, 3);
const energy = () => simulation.organisms.reduce((sum,member) => sum + member.energy,0) + [...simulation.bonds.values()].reduce((sum,bond)=>sum+bond.reserve,0) + [...simulation.componentReserves.values()].reduce((sum,value)=>sum+value,0);
const before = energy();
shrinkAtRiskComponents(simulation);
assert.equal(simulation.shrinkStats.reclaimed,0, 'no action without history');
simulation.shrinkHistory.set(key,{total:before + 2, drain:2, samples:8});
shrinkAtRiskComponents(simulation);
assert.equal(tail.alive,false);
assert.equal(simulation.bonds.size,3, 'closed core must remain intact');
assert.equal(simulation.shrinkStats.reclaimed,1);
assert.ok(Math.abs(before - energy() - simulation.shrinkStats.energyLost)<1e-9);
assert.equal([...simulation.componentReserves.values()][0],3);
assert.ok(simulation.organisms.filter(member=>member.alive).every(member=>member.lastShrinkAge===100));
shrinkAtRiskComponents(simulation);
assert.equal(simulation.shrinkStats.reclaimed,1);
simulation.config.bond.adaptiveShrinking.enabled = false;
shrinkAtRiskComponents(simulation);
assert.equal(simulation.shrinkStats.reclaimed,1);
console.log('Forecast gating, terminal selection, core preservation, conservation, reserve retention and disabling passed.');
process.exit(0);
