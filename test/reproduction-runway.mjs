import assert from 'node:assert/strict';
import {Simulation} from '../server/simulation/simulation.js';
import {reproductionRunway,recordRunwayBirth} from '../server/simulation/reproduction-runway.js';
const sim=new Simulation();sim.stop();
sim.config.bond.adaptiveMorphology.enabled=true;
Object.assign(sim.config.bond.reproductionRunway,{enabled:true,horizonTicks:24});
sim.organisms=sim.organisms.slice(0,3);sim.bonds.clear();
const [a,b,c]=sim.organisms;
for(const [m,x] of [[a,10],[b,11],[c,40]])Object.assign(m,{x,y:10,energy:140,
  lastOperatingExpense:4,foragingOperatingCost:4,foragingIncome:0});
sim.bonds.set(sim.bondKey(a.id,b.id),{firstId:a.id,secondId:b.id,reserve:3,strength:1});
const before=sim.organisms.map(m=>m.energy);
assert.equal(reproductionRunway(sim,a).allowed,false,'declining energy cannot fund another mouth');
assert.deepEqual(sim.organisms.map(m=>m.energy),before,'forecast cannot debit or grant energy');
a.energy=200;b.energy=200;
assert.equal(reproductionRunway(sim,a).allowed,true,'an affordable birth remains possible');
b.energy=1;assert.equal(reproductionRunway(sim,a).allowed,false,'hungry neighbour has priority');
b.energy=200;c.energy=1;assert.equal(reproductionRunway(sim,a).allowed,true,'distant hunger is not a global veto');
a.energy=200;b.energy=200;a.foragingIncome=5;b.foragingIncome=5;
assert.equal(reproductionRunway(sim,a).allowed,true,'earned income can reduce the forecast deficit');
const child={id:999,energy:100,alive:true,x:10,y:11,foragingOperatingCost:4};
const beforeBirth=reproductionRunway(sim,b);
a.energy=100;recordRunwayBirth(sim,a,child);
assert.equal(sim.reproductionRunwayBirths.length,1);
const pending=reproductionRunway(sim,b);
assert.equal(pending.balance,beforeBirth.balance,'splitting parent energy is not new income');
assert.ok(Math.abs(pending.required-beforeBirth.required-96)<1e-8,'pending newborn adds its own future operating demand');
sim.organisms.push(child);sim.bonds.set(sim.bondKey(b.id,child.id),{firstId:b.id,secondId:child.id,strength:1,reserve:3});
const materialized=reproductionRunway(sim,b);
assert.equal(pending.balance,materialized.balance,'materialized children cannot be counted twice');
assert.ok(Number.isFinite(materialized.required));
sim.config.bond.reproductionRunway.enabled=false;
assert.deepEqual(reproductionRunway(sim,a),{allowed:true},'off switch must bypass all runway state');
console.log('Reproduction runway: local deficits, earned income, pending births, no transfers and off switch passed.');
process.exit(0);
