import assert from 'node:assert/strict';
import {Simulation} from '../server/simulation/simulation.js';
const simulation=new Simulation();simulation.stop();simulation.setSeed(160103);
Object.assign(simulation.config.bond.adaptiveMorphology,{enabled:true,paidFormationEnabled:true,renewalEnabled:true});
simulation.organisms=simulation.organisms.slice(0,2);simulation.bonds.clear();
const [a,b]=simulation.organisms;
a.x=10;a.y=10;b.x=11;b.y=10;a.energy=100;b.energy=100;
a.brainExecution={effectors:{bind:1}};b.brainExecution={effectors:{bind:1}};
simulation.config.bond.buddingCandidateTicks=1;
a.energy-=2;simulation.seedStructuralBond(a.id,b.id,2);
simulation.updateBonds();
assert.equal(simulation.bonds.size,1);
assert.ok(Math.abs(a.energy+b.energy+[...simulation.bonds.values()][0].reserve-200)<1e-9,'formation reserve must be paid');
simulation.organisms=simulation.organisms.slice(0,1);
simulation.organisms.push(b);simulation.bonds.clear();
simulation.bonds.set(simulation.bondKey(a.id,b.id),{firstId:a.id,secondId:b.id,strength:1,reserve:5});
a.age=Math.ceil(simulation.config.organism.maxAge*.6);a.energy=300;b.energy=20;b.age=0;
a.canReproduce=()=>false;b.canReproduce=()=>false;
simulation.getReproductionOpportunity=()=>({opportunity:1});
simulation.morphologyStats={};simulation.structuralBirthSeeds.clear();
const before=a.energy+b.energy;
simulation.handleReproduction();
assert.equal(simulation.organisms.length,3);
assert.equal(simulation.morphologyStats.renewalBirths,1);
const total=simulation.organisms.reduce((sum,member)=>sum+member.energy,0)+[...simulation.structuralBirthSeeds.values()].reduce((sum,value)=>sum+value,0);
assert.ok(Math.abs(before-total)<1e-9,'renewal and pending connections must conserve invested energy');
console.log('Paid formation and budgeted local generational renewal passed.');
process.exit(0);
